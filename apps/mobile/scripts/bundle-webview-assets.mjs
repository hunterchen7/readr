#!/usr/bin/env node
/**
 * Build WebView assets from source and npm deps.
 *
 *   renderer/index.ts  → IIFE bundle for the EPUB reader (our new renderer)
 *   pdfjs-dist         → pdf.min.mjs + pdf.worker.min.mjs for the PDF reader
 *
 * Output: assets/js/  (loaded by the WebView via file:///android_asset/js/)
 * Run:    node scripts/bundle-webview-assets.mjs
 */
import { build } from "esbuild";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import { createRequire } from "module";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const outDir = join(root, "assets", "js");
mkdirSync(outDir, { recursive: true });

// ─── renderer/index.ts → renderer-bundle.js ─────────────────────────
// The single-bundle EPUB reader that replaces foliate-js. It inlines
// fflate for ZIP parsing, foliate's epubcfi.js for CFI interop, and
// our own parser / host / layout / annotations / search modules.
await build({
  entryPoints: [join(root, "webview-src", "renderer", "index.ts")],
  bundle: true,
  format: "iife",
  outfile: join(outDir, "renderer-bundle.js"),
  platform: "browser",
  target: "es2020",
  minify: true,
  sourcemap: false,
});
console.log("✓ renderer-bundle.js");

// Also emit the bundle as a TypeScript module whose default export is
// the minified JS as a string. The RN reader screen imports this and
// inlines it inside the WebView HTML, so renderer-code changes flow
// through Metro (no APK rebuild needed to iterate).
{
  const bundleText = readFileSync(join(outDir, "renderer-bundle.js"), "utf8");
  // Escape ONLY the backticks and backslashes — the raw bundle already
  // contains all the quotes/newlines we need.
  const escaped = bundleText.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  const out = `// GENERATED by scripts/bundle-webview-assets.mjs — do not edit by hand.\nexport const RENDERER_BUNDLE = \`${escaped}\`;\n`;
  writeFileSync(
    join(root, "components", "reader", "renderer-bundle.generated.ts"),
    out,
  );
  console.log("✓ components/reader/renderer-bundle.generated.ts");
}

// ─── pdfjs-dist ────────────────────────────────────────────────────
const require = createRequire(import.meta.url);
const pdfjsDir = join(dirname(require.resolve("pdfjs-dist/package.json")), "build");

copyFileSync(join(pdfjsDir, "pdf.min.mjs"), join(outDir, "pdf.min.mjs"));
copyFileSync(join(pdfjsDir, "pdf.worker.min.mjs"), join(outDir, "pdf.worker.min.mjs"));
console.log("✓ pdf.min.mjs + pdf.worker.min.mjs");

// ─── Copy to android assets if prebuild has run ────────────────────
const androidOut = join(root, "android", "app", "src", "main", "assets", "js");
try {
  mkdirSync(androidOut, { recursive: true });
  for (const f of ["renderer-bundle.js", "pdf.min.mjs", "pdf.worker.min.mjs"]) {
    copyFileSync(join(outDir, f), join(androidOut, f));
  }
  console.log("✓ Copied to android assets");
} catch {}
