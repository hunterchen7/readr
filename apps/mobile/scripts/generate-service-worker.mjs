#!/usr/bin/env node
/**
 * Generate a service worker + precache manifest for the exported
 * Expo Web bundle. Runs after `expo export` (and after the HTML
 * patcher) so it can walk `dist/` and discover the hashed chunk
 * filenames Metro produced on this run.
 *
 * Strategy:
 *   - precache: index.html, manifest.json, pdf.worker.min.mjs, the
 *     main entry-*.js, and every hashed chunk under _expo/. This is
 *     the full "app shell" — enough to boot offline and open any
 *     route the router can navigate to.
 *   - runtime: anything else same-origin is stale-while-revalidate.
 *   - API (/api/): always network. The service worker is an offline
 *     *reader* safety net, not a sync proxy — local-db.web already
 *     handles offline mutations via the IDB sync queue.
 *
 * The version string is derived from the entry bundle's filename
 * hash so a new export invalidates the old cache automatically.
 *
 * Run: node scripts/generate-service-worker.mjs [dist-dir]
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from "fs";
import { join, relative, sep, posix } from "path";

const distDir = process.argv[2] || "dist";
const root = join(process.cwd(), distDir);

if (!existsSync(root)) {
  console.error(`✗ dist dir not found: ${root}`);
  process.exit(1);
}

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const s = statSync(p);
    if (s.isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

// Collect every file shipped in dist and build URL paths with
// forward slashes so we can match fetch requests.
const all = walk(root).map((p) => "/" + relative(root, p).split(sep).join(posix.sep));

// Precache the shell: index, manifest, pdf worker, every _expo/
// chunk, the sw itself, and any top-level static files like icons.
const precache = new Set();
precache.add("/");
precache.add("/index.html");
if (all.includes("/manifest.json")) precache.add("/manifest.json");
if (all.includes("/pdf.min.mjs")) precache.add("/pdf.min.mjs");
if (all.includes("/pdf.worker.min.mjs")) precache.add("/pdf.worker.min.mjs");
if (all.includes("/favicon.ico")) precache.add("/favicon.ico");
for (const path of all) {
  if (path.startsWith("/_expo/")) precache.add(path);
  if (path.startsWith("/assets/")) precache.add(path);
}

// Version = hash of the concatenated precache list so a new build
// (different chunk filenames) invalidates the old cache.
const version = Buffer.from(Array.from(precache).sort().join("|"))
  .toString("base64")
  .replace(/[^a-zA-Z0-9]/g, "")
  .slice(0, 16);

const sw = `/**
 * Readr service worker — generated by scripts/generate-service-worker.mjs.
 *
 * Pre-caches the full exported app shell (${precache.size} files) on
 * install and serves cached copies first for hashed chunks. Network-
 * first for HTML/navigation so newly-deployed versions reach the
 * user as soon as they're back online. API calls bypass the SW
 * entirely.
 *
 * Do not edit by hand — next \`pnpm -C apps/mobile web:build\` run
 * will overwrite it.
 */
const VERSION = ${JSON.stringify(version)};
const CACHE_NAME = "readr-shell-" + VERSION;
const PRECACHE = ${JSON.stringify(Array.from(precache).sort(), null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    // Use {cache: "reload"} so the SW always fetches fresh bytes
    // on install rather than whatever HTTP cache has for these.
    await Promise.all(
      PRECACHE.map((url) =>
        cache.add(new Request(url, { cache: "reload" })).catch(() => {
          // Tolerate missing files (e.g. /assets/ if the exporter
          // moved their layout) so a single 404 doesn't poison the
          // whole install.
        }),
      ),
    );
    self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(
      keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)),
    );
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;

  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // API calls and auth go through untouched. The SW is for offline
  // reading/navigation, not for standing in for the backend.
  if (url.pathname.startsWith("/api/")) return;

  // Hashed assets under /_expo/ are immutable — cache-first. On a
  // miss (different hash from last install), fetch + cache so the
  // next session has it offline.
  if (url.pathname.startsWith("/_expo/") || url.pathname.startsWith("/assets/")) {
    event.respondWith((async () => {
      const cached = await caches.match(req);
      if (cached) return cached;
      try {
        const res = await fetch(req);
        if (res.ok) {
          const cache = await caches.open(CACHE_NAME);
          cache.put(req, res.clone());
        }
        return res;
      } catch (err) {
        // Nothing we can do — propagate the network failure.
        throw err;
      }
    })());
    return;
  }

  // Navigation / HTML: network-first with cache fallback. If the
  // network is down and we don't have the exact URL cached, fall
  // back to the SPA shell — expo-router resolves the route from
  // history once the bundle boots.
  event.respondWith((async () => {
    try {
      const res = await fetch(req);
      if (res.ok && req.headers.get("accept")?.includes("text/html")) {
        const cache = await caches.open(CACHE_NAME);
        cache.put(req, res.clone());
      }
      return res;
    } catch {
      const cached = await caches.match(req);
      if (cached) return cached;
      const shell = await caches.match("/index.html");
      if (shell) return shell;
      return new Response("Offline", { status: 503, statusText: "Offline" });
    }
  })());
});
`;

writeFileSync(join(root, "sw.js"), sw);
console.log(`✓ sw.js (${precache.size} precached, version=${version})`);
